#!/usr/bin/env node
// Extracts the JavaScript from every Code node in workflows/*.json into src/*.js,
// so the logic can be read and reviewed on GitHub without opening n8n.
// The workflow JSON is the source of truth: edit the code in n8n, export the
// workflow into workflows/, then run `node scripts/export-code.js`.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FILES = {
  'job-tracker.json': {
    'Pre-filter job emails': 'prefilter.js',
    'Prepare LLM Input': 'prepare-llm-input.js',
    'Decide': 'decide.js',
    'Build Discord message': 'build-discord-message.js',
  },
  'weekly-digest.json': {
    'Find stale applications': 'digest-find-stale.js',
    'Build weekly summary': 'digest-summary.js',
  },
};

const outDir = path.join(ROOT, 'src');
fs.mkdirSync(outDir, { recursive: true });

let count = 0;
for (const [wfFile, nodes] of Object.entries(FILES)) {
  const wf = JSON.parse(fs.readFileSync(path.join(ROOT, 'workflows', wfFile), 'utf8'));
  for (const [nodeName, outFile] of Object.entries(nodes)) {
    const node = wf.nodes.find((n) => n.name === nodeName);
    if (!node) throw new Error(`Node "${nodeName}" not found in ${wfFile}`);
    const header =
      `// n8n Code node: "${nodeName}" (workflows/${wfFile})\n` +
      `// Generated by scripts/export-code.js. Edit the workflow, not this file.\n\n`;
    fs.writeFileSync(path.join(outDir, outFile), header + node.parameters.jsCode);
    count++;
  }
}
console.log(`Exported ${count} Code nodes to src/`);
